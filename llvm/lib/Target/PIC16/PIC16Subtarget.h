#ifndef LLVM_LIB_TARGET_PIC16_PIC16SUBTARGET_H
#define LLVM_LIB_TARGET_PIC16_PIC16SUBTARGET_H

#include "PIC16FrameLowering.h"
#include "PIC16ISelLowering.h"
#include "PIC16InstrInfo.h"
#include "llvm/CodeGen/SelectionDAGTargetInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include "llvm/IR/DataLayout.h"
#include "llvm/MC/MCInstrItineraries.h"

#define GET_SUBTARGETINFO_HEADER
#include "PIC16GenSubtargetInfo.inc"

namespace llvm {
class PIC16Subtarget : public PIC16GenSubtargetInfo {
protected:
  SelectionDAGTargetInfo TSInfo;
  PIC16RegisterInfo RegInfo;
  PIC16InstrInfo InstrInfo;
  PIC16FrameLowering FrameLowering;
  PIC16TargetLowering TLInfo;

public:
  /// This constructor initializes the data members to match that
  /// of the specified triple.
  PIC16Subtarget(const Triple &TT, StringRef CPU, StringRef FS,
                const TargetMachine &TM);

  /// ParseSubtargetFeatures - Parses features string setting specified
  /// subtarget options.  Definition of function is auto generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  PIC16Subtarget &initializeSubtargetDependencies(const Triple &TT,
                                                  StringRef CPU, StringRef FS,
                                                  const TargetMachine &TM);

  const SelectionDAGTargetInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }

  const PIC16InstrInfo *getInstrInfo() const override {
    return &InstrInfo;
  }

  const TargetFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }

  const PIC16RegisterInfo *getRegisterInfo() const override {
    return &RegInfo;
  }

  const PIC16TargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }

  /// getMaxInlineSizeThreshold - Returns the maximum memset / memcpy size
  /// that still makes it profitable to inline the call.
  unsigned getMaxInlineSizeThreshold() const {
    return 64;
  }
};
}

#endif // end LLVM_LIB_TARGET_PIC16_PIC16SUBTARGET_H
