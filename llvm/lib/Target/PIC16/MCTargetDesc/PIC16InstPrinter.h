#ifndef LLVM_LIB_TARGET_PIC16_INSTPRINTER_PIC16INSTPRINTER_H
#define LLVM_LIB_TARGET_PIC16_INSTPRINTER_PIC16INSTPRINTER_H

#include "llvm/MC/MCInstPrinter.h"

namespace llvm {

class PIC16InstPrinter : public MCInstPrinter {
public:
  PIC16InstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                  const MCRegisterInfo &MRI);

  // Autogenerated by tblgen.
  std::pair<const char *, uint64_t> getMnemonic(const MCInst &MI) const override;
  void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &O);
  static const char *getRegisterName(MCRegister RegNo);

  void printRegName(raw_ostream &OS, MCRegister RegNo) override;
  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override;

  bool printAliasInstr(const MCInst *MI, uint64_t Address, raw_ostream &OS);
  void printCustomAliasOperand(const MCInst *MI, uint64_t Address,
                               unsigned OpIdx, unsigned PrintMethodIdx,
                               raw_ostream &O);

private:
  void printOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
};
} // end namespace llvm

#endif // end LLVM_LIB_TARGET_PIC16_INSTPRINTER_PIC16INSTPRINTER_H
